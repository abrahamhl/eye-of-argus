const VIEW = { minLat: 51.975, maxLat: 52.005, minLon: 5.855, maxLon: 5.925 };

const TABS = [
  { id: 'overview', label: 'OVERVIEW' },
  { id: 'crowd', label: 'CROWD' },
  { id: 'calm', label: 'CALM' },
  { id: 'social', label: 'SOCIAL' },
  { id: 'forecast', label: 'FORECAST' },
  { id: 'evidence', label: 'EVIDENCE' },
  { id: 'licence', label: 'LICENCE' },
  { id: 'privacy', label: 'PRIVACY' },
  { id: 'analyst', label: 'ANALYST' },
  { id: 'brief', label: 'INVESTORS · XYZ' },
];

const state = {
  data: null,
  profile: 'COMMERCIAL_SAFE',
  mode: 'CALM',
  venueId: null,
  tab: 'overview',
};

const BAND_COLOR = {
  LOW: '#4ade80',
  MODERATE: '#ffb454',
  HIGH: '#f87171',
  'VERY HIGH': '#ff5c5c',
  UNAVAILABLE: '#475569',
};

function colorForScore(score) {
  if (score === null || score === undefined) return BAND_COLOR.UNAVAILABLE;
  if (score < 25) return BAND_COLOR.LOW;
  if (score < 50) return BAND_COLOR.MODERATE;
  if (score < 75) return BAND_COLOR.HIGH;
  return BAND_COLOR['VERY HIGH'];
}

function q(id) { return document.getElementById(id); }

function place() {
  return state.data.profiles[state.profile].places.find((p) => p.id === state.venueId);
}

function profileData() { return state.data.profiles[state.profile]; }

