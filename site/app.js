/* ----------------------------------------------------------------- venues */

function renderVenues() {
  const ranked = profileData().ranking[state.mode];
  q('venue-list').innerHTML = ranked.map((id) => {
    const p = profileData().places.find((x) => x.id === id);
    const bars = ['crowd', 'calm', 'social'].map((s) => {
      const v = p.signals[s].score ?? 0;
      return `<span class="bar"><i style="width:${v}%;background:${colorForScore(v)}"></i></span>`;
    }).join('');
    return `<button class="venue ${id === state.venueId ? 'active' : ''}" data-venue="${id}">
      <div class="name">${escapeHtml(p.name)}</div>
      <div class="sub">rank #${ranked.indexOf(id) + 1} · ${state.mode} · crowd ${fmt(p.signals.crowd.score)} · calm ${fmt(p.signals.calm.score)}</div>
      <div class="bars">${bars}</div>
    </button>`;
  }).join('');
  q('venue-list').querySelectorAll('.venue').forEach((b) => b.addEventListener('click', () => {
    state.venueId = b.dataset.venue;
    renderVenues();
    renderMetrics();
  }));

  q('legend').innerHTML = ['LOW', 'MODERATE', 'HIGH', 'VERY HIGH']
    .map((b) => `<div class="row"><span class="swatch" style="background:${BAND_COLOR[b]}"></span>${b}</div>`)
    .join('') + `<div class="row muted">hatched = suppressed (k&lt;${state.data.privacy.k}) or unavailable</div>`;
}

/* ---------------------------------------------------------------- metrics */

function metricCard(label, signal, accent) {
  const bandClass = String(signal.band).replace(' ', '-');
  const range = signal.range ? `${signal.range.low}–${signal.range.high}` : 'n/a';
  const pct = signal.score === null ? 0 : signal.score;
  const dc = String(signal.dataClass ?? 'unknown').toUpperCase();
  return `<div class="metric">
    <div class="head">
      <span class="label">${label}</span>
      <span class="band ${bandClass}">${signal.band}</span>
    </div>
    <div class="value" style="color:${accent}">${fmt(signal.score)}</div>
    <div class="gauge"><i style="width:${pct}%;background:${accent}"></i></div>
    <div class="foot"><span>range ${range}</span><span>${dc === 'LIVE' ? 'live' : dc} · evidence conf ${signal.confidence}</span></div>
  </div>`;
}

function confidenceCard(signal) {
  const pct = Math.round((signal.confidence ?? 0) * 100);
  const stateLabel = signal.confidenceState ?? 'UNKNOWN';
  return `<div class="metric">
    <div class="head"><span class="label">CONFIDENCE (evidence quality)</span><span class="band">${stateLabel}</span></div>
    <div class="value" style="color:var(--cyan)">${signal.confidence}</div>
    <div class="gauge"><i style="width:${pct}%;background:var(--cyan)"></i></div>
    <div class="foot"><span>not a crowd score</span><span>${signal.contributions.filter((c) => c.included).length} contributors</span></div>
  </div>`;
}

function renderMetrics() {
  const p = place();
  if (!p) { q('metrics').innerHTML = ''; return; }
  q('metrics').innerHTML = `
    <h2>${escapeHtml(p.name)}</h2>
    ${metricCard('CROWD INDEX', p.signals.crowd, colorForScore(p.signals.crowd.score))}
    ${metricCard('CALM INDEX', p.signals.calm, colorForScore(p.signals.calm.score))}
    ${metricCard('SOCIAL OPPORTUNITY', p.signals.social, colorForScore(p.signals.social.score))}
    ${confidenceCard(p.signals.crowd)}
  `;
}

