let canvas, ctx, sweep = 0;

function initCanvas() {
  canvas = q('radar');
  ctx = canvas.getContext('2d');
  const resize = () => {
    const r = canvas.getBoundingClientRect();
    const dpr = window.devicePixelRatio || 1;
    canvas.width = Math.max(1, Math.floor(r.width * dpr));
    canvas.height = Math.max(1, Math.floor(r.height * dpr));
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  };
  resize();
  window.addEventListener('resize', resize);
  const loop = (ts) => { sweep = ts / 1000; draw(); requestAnimationFrame(loop); };
  requestAnimationFrame(loop);
}

function project(lat, lon, w, h) {
  const x = ((lon - VIEW.minLon) / (VIEW.maxLon - VIEW.minLon)) * w;
  const y = h - ((lat - VIEW.minLat) / (VIEW.maxLat - VIEW.minLat)) * h;
  return { x, y };
}

function activeMetric() {
  if (state.tab === 'crowd' || state.tab === 'calm' || state.tab === 'social') return state.tab;
  return null;
}

function draw() {
  const r = canvas.getBoundingClientRect();
  const w = r.width, h = r.height;
  ctx.clearRect(0, 0, w, h);

  // background grid
  ctx.strokeStyle = 'rgba(55,224,255,0.08)';
  ctx.lineWidth = 1;
  for (let x = 0; x <= w; x += 40) { ctx.beginPath(); ctx.moveTo(x, 0); ctx.lineTo(x, h); ctx.stroke(); }
  for (let y = 0; y <= h; y += 40) { ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(w, y); ctx.stroke(); }

  if (state.tab === 'privacy') { drawPrivacy(w, h); drawSweep(w, h); return; }

  // heat field per destination
  const metric = activeMetric();
  for (const p of profileData().places) {
    const pos = project(p.lat, p.lon, w, h);
    const score = p.signals[metric ?? 'crowd'].score ?? 0;
    const radius = 60 + score * 0.9;
    const grad = ctx.createRadialGradient(pos.x, pos.y, 0, pos.x, pos.y, radius);
    const col = colorForScore(score);
    grad.addColorStop(0, hexA(col, 0.42));
    grad.addColorStop(1, hexA(col, 0));
    ctx.fillStyle = grad;
    ctx.beginPath(); ctx.arc(pos.x, pos.y, radius, 0, Math.PI * 2); ctx.fill();

    // crosshair rings
    ctx.strokeStyle = hexA(col, 0.5);
    ctx.beginPath(); ctx.arc(pos.x, pos.y, 18 + Math.sin(sweep * 2 + p.lat) * 3, 0, Math.PI * 2); ctx.stroke();

    // blip
    const selected = p.id === state.venueId;
    ctx.fillStyle = col;
    ctx.beginPath(); ctx.arc(pos.x, pos.y, selected ? 7 : 5, 0, Math.PI * 2); ctx.fill();
    if (selected) {
      ctx.strokeStyle = '#37e0ff'; ctx.lineWidth = 1.5;
      ctx.beginPath(); ctx.arc(pos.x, pos.y, 14, 0, Math.PI * 2); ctx.stroke();
    }

    ctx.fillStyle = '#dbe6f2';
    ctx.font = '11px ui-monospace, monospace';
    ctx.fillText(`${p.name.split(' ').slice(0, 2).join(' ')}  ${fmt(score)} ${p.signals[metric ?? 'crowd'].band}`, pos.x + 14, pos.y - 10);
    ctx.fillStyle = 'rgba(128,147,168,0.9)';
    ctx.font = '10px ui-monospace, monospace';
    ctx.fillText(`conf ${p.signals[metric ?? 'crowd'].confidence}`, pos.x + 14, pos.y + 4);
  }

  drawSweep(w, h);
}

function drawSweep(w, h) {
  const cx = w / 2, cy = h / 2, len = Math.max(w, h);
  const a = sweep % (Math.PI * 2);
  const grad = ctx.createLinearGradient(cx, cy, cx + Math.cos(a) * len, cy + Math.sin(a) * len);
  grad.addColorStop(0, 'rgba(55,224,255,0.35)');
  grad.addColorStop(1, 'rgba(55,224,255,0)');
  ctx.strokeStyle = grad;
  ctx.lineWidth = 2;
  ctx.beginPath(); ctx.moveTo(cx, cy); ctx.lineTo(cx + Math.cos(a) * len, cy + Math.sin(a) * len); ctx.stroke();
}

function drawPrivacy(w, h) {
  const { rawCells, k } = state.data.privacy;
  const cols = 3, rows = Math.ceil(rawCells.length / cols);
  const pad = 24;
  const cw = (w - pad * 2) / cols, ch = (h - pad * 2) / rows;
  rawCells.forEach((cell, i) => {
    const x = pad + (i % cols) * cw, y = pad + Math.floor(i / cols) * ch;
    const suppressed = cell.count < k;
    ctx.save();
    ctx.beginPath(); ctx.rect(x + 6, y + 6, cw - 12, ch - 12); ctx.clip();
    if (suppressed) {
      ctx.fillStyle = 'rgba(71,85,105,0.35)';
      ctx.fillRect(x + 6, y + 6, cw - 12, ch - 12);
      ctx.strokeStyle = 'rgba(128,147,168,0.6)'; ctx.lineWidth = 1;
      for (let s = -ch; s < cw; s += 10) {
        ctx.beginPath(); ctx.moveTo(x + 6 + s, y + ch - 6); ctx.lineTo(x + 6 + s + ch, y + 6); ctx.stroke();
      }
      ctx.fillStyle = '#8093a8';
    } else {
      ctx.fillStyle = hexA(colorForScore(cell.count), 0.5);
      ctx.fillRect(x + 6, y + 6, cw - 12, ch - 12);
      ctx.fillStyle = '#dbe6f2';
    }
    ctx.restore();
    ctx.strokeStyle = '#27384a';
    ctx.strokeRect(x + 6, y + 6, cw - 12, ch - 12);
    ctx.fillStyle = '#dbe6f2'; ctx.font = '11px ui-monospace, monospace';
    ctx.fillText(suppressed ? 'SUPPRESSED' : `RELEASED`, x + 14, y + 24);
    ctx.fillStyle = '#8093a8'; ctx.font = '10px ui-monospace, monospace';
    ctx.fillText(suppressed ? `count < k (${k}) withheld` : `occupancy band`, x + 14, y + 40);
  });
}

/* ------------------------------------------------------------------ lower */

function renderLower() {
  const p = place();
  const lower = q('lower');
  switch (state.tab) {
    case 'forecast': return renderForecast(lower, p);
    case 'evidence': return renderEvidence(lower, p);
    case 'licence': return renderLicence(lower);
    case 'privacy': return renderPrivacy(lower);
    case 'analyst': return renderAnalyst(lower);
    case 'brief': return renderBrief(lower);
    case 'crowd': case 'calm': case 'social':
      return renderMetricDetail(lower, p, state.tab);
    default:
      return renderOverview(lower);
  }
}

